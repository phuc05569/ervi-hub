"""Deterministic single-file bundler for the RNG RollAttacks hub.

python build.py         -> build/Ervi_Hub.luau (+ .map.json)
python build.py --test  -> build/tests.luau (pure modules + specs, runnable with tools/luau/luau.exe)
Same sources always produce byte-identical output (no timestamps).
"""
import hashlib
import json
import pathlib
import sys

ROOT = pathlib.Path(__file__).parent
VERSION = "2.4.0"
APP_MODULES = ["Scope", "Rarity", "AutoRoll", "Settings", "Theme", "Ui", "Game", "RollAdapter", "Cyborg", "RollObserver", "Session", "Prompts", "App"]
PURE_MODULES = ["Scope", "Rarity", "AutoRoll", "Settings"]


def read(path):
    return path.read_text(encoding="utf-8").replace("\r\n", "\n")


def bundle(modules, entry, out_name, title):
    sources = [(name, f"src/{name}.luau", read(ROOT / "src" / f"{name}.luau")) for name in modules]
    if entry != "App":
        for spec in sorted((ROOT / "tests").glob("*.luau")):
            sources.append((spec.stem, f"tests/{spec.name}", read(spec)))
    digest = hashlib.sha256("".join(f"{n}\0{s}" for n, _, s in sources).encode()).hexdigest()[:12]
    build_id = f"{VERSION}+{digest}"
    sources.insert(0, ("Build", "(generated)", f'return {{ version = "{VERSION}", id = "{build_id}" }}\n'))

    out = [
        f"-- {title} | build {build_id}",
        "-- Generated by build.py from src/*.luau. Edit the modules, not this file.",
        "local __sources, __cache, __realRequire = {}, {}, require",
        "local function __require(name)",
        "\tif typeof(name) == \"Instance\" then return __realRequire(name) end -- game ModuleScripts",
        "\tlocal hit = __cache[name]",
        "\tif hit ~= nil then return hit end",
        "\tlocal fn = __sources[name]",
        '\tif not fn then error("[RNG Hub] missing module " .. tostring(name), 2) end',
        "\tlocal result = fn(__require)",
        "\t__cache[name] = result == nil and true or result",
        "\treturn result",
        "end",
    ]
    smap = {}
    for name, path, src in sources:
        out.append(f'__sources["{name}"] = function(require) -- {path}')
        start = len(out) + 1
        out.extend(src.rstrip("\n").split("\n"))
        smap[name] = {"file": path, "bundleStart": start, "bundleEnd": len(out)}
        out.append("end")
    out.append(f'return __require("{entry}")')
    text = "\n".join(out) + "\n"
    (ROOT / "build").mkdir(exist_ok=True)
    (ROOT / "build" / out_name).write_text(text, encoding="utf-8", newline="\n")
    (ROOT / "build" / (out_name + ".map.json")).write_text(json.dumps({"build": build_id, "modules": smap}, indent=1), encoding="utf-8")
    print(f"{out_name}: {len(out) + 1} lines, build {build_id}, sha256 {hashlib.sha256(text.encode()).hexdigest()}")


def smoke():
    """Headless run of the real hub bundle inside tests/smoke/MockEngine (needs build/rbx_api.luau)."""
    part = lambda p: read(ROOT / p)
    text = (
        f"local API = (function()\n{part('build/rbx_api.luau')}\nend)()\n"
        f"local makeEngine = (function()\n{part('tests/smoke/MockEngine.luau')}\nend)()\n"
        f"local hubFn = function()\n{part('build/Ervi_Hub.luau')}\nend\n"
        f"local driver = (function()\n{part('tests/smoke/driver.luau')}\nend)()\n"
        "driver(API, makeEngine, hubFn)\n"
    )
    (ROOT / "build" / "smoke.luau").write_text(text, encoding="utf-8", newline="\n")
    print("smoke.luau written")


if __name__ == "__main__":
    if "--smoke" in sys.argv:
        bundle(APP_MODULES, "App", "Ervi_Hub.luau", "Ervi Hub")
        smoke()
    elif "--test" in sys.argv:
        bundle(PURE_MODULES, "run", "tests.luau", "RNG Hub test bundle")
    else:
        bundle(APP_MODULES, "App", "Ervi_Hub.luau", "Ervi Hub")

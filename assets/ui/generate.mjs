// Generates assets/ui/*.png and src/UiAssets.luau (base64 PNGs + atlas map).
// Run from the repo root, with lucide-static@0.460.0 and @resvg/resvg-js@2.6.2 resolvable:
//   NODE_PATH=<dir>/node_modules node assets/ui/generate.mjs
// Logo polygons come from src/LogoGeometry.luau, so the image cannot drift from the native mark.
import fs from "node:fs";
import path from "node:path";
import { createRequire } from "node:module";

const require = createRequire(path.join(process.env.NODE_PATH || process.cwd(), "x.js"));
const { Resvg } = require("@resvg/resvg-js");
const lucideDir = path.join(path.dirname(require.resolve("lucide-static/package.json")), "icons");

const ROOT = process.cwd();
const OUT = path.join(ROOT, "assets", "ui");

// Navigation id -> Lucide icon. Keep in sync with Ui.ICONS consumers (App/Expansion page ids).
const ICONS = [
	["roll", "dices"], ["styles", "layers"], ["dash", "house"], ["combat", "swords"],
	["visuals", "eye"], ["player", "user-round"], ["world", "globe"], ["safe", "shield"],
	["teleports", "map-pin"], ["utility", "wrench"], ["settings", "settings"], ["diag", "activity"],
	["session", "server"], ["search", "search"], ["close", "x"], ["minimize", "minus"],
	["chevron", "chevron-down"], ["generic", "circle-dot"],
];
const CELL = 56, ICON = 48, PAD = (CELL - ICON) / 2, COLS = 6;

function render(svg, width) {
	return new Resvg(svg, { fitTo: { mode: "width", value: width }, background: "rgba(0,0,0,0)" }).render().asPng();
}

// --- icon atlas
const rows = Math.ceil(ICONS.length / COLS);
let atlas = `<svg xmlns="http://www.w3.org/2000/svg" width="${COLS * CELL}" height="${rows * CELL}" viewBox="0 0 ${COLS * CELL} ${rows * CELL}">`;
const map = [];
ICONS.forEach(([id, name], i) => {
	const src = fs.readFileSync(path.join(lucideDir, name + ".svg"), "utf8");
	const inner = src.replace(/^[\s\S]*?<svg[^>]*>/, "").replace(/<\/svg>\s*$/, "");
	const x = (i % COLS) * CELL + PAD, y = Math.floor(i / COLS) * CELL + PAD;
	atlas += `<svg x="${x}" y="${y}" width="${ICON}" height="${ICON}" viewBox="0 0 24 24" fill="none" stroke="#FFFFFF" stroke-width="2" stroke-linecap="round" stroke-linejoin="round">${inner}</svg>`;
	map.push(`${id}={${x},${y}}`);
});
atlas += "</svg>";
const iconsPng = render(atlas, COLS * CELL);

// --- logo from the authoritative geometry
const geo = fs.readFileSync(path.join(ROOT, "src", "LogoGeometry.luau"), "utf8");
const W = Number(geo.match(/width = (\d+)/)[1]), H = Number(geo.match(/height = (\d+)/)[1]);
const polys = [...geo.matchAll(/\{\{([^\n]*?)\}\},/g)].map((m) =>
	[...m[1].matchAll(/(-?\d+), (-?\d+)/g)].map((p) => `${p[1]},${p[2]}`).join(" "));
if (polys.length !== 3) throw new Error("expected three logo polygons, got " + polys.length);
const logoSvg = `<svg xmlns="http://www.w3.org/2000/svg" width="${W}" height="${H}" viewBox="0 0 ${W} ${H}">` +
	polys.map((p) => `<polygon points="${p}" fill="#FFFFFF"/>`).join("") + "</svg>";
const logoPng = render(logoSvg, 256);

fs.mkdirSync(OUT, { recursive: true });
fs.writeFileSync(path.join(OUT, "icons.png"), iconsPng);
fs.writeFileSync(path.join(OUT, "logo.png"), logoPng);
fs.writeFileSync(path.join(OUT, "logo.svg"), logoSvg + "\n");
fs.copyFileSync(path.join(lucideDir, "..", "LICENSE"), path.join(OUT, "LUCIDE_LICENSE.txt"));

const lua = `-- GENERATED by assets/ui/generate.mjs. Do not edit; rerun the generator.
-- Icons: Lucide (ISC, see assets/ui/LUCIDE_LICENSE.txt). Logo: src/LogoGeometry.luau polygons.
return {
	version = "${Buffer.from(iconsPng).length}-${Buffer.from(logoPng).length}",
	cell = ${ICON},
	icons = { ${map.join(", ")} },
	logoSize = { 256, ${Math.round((256 * H) / W)} },
	iconsPng = "${Buffer.from(iconsPng).toString("base64")}",
	logoPng = "${Buffer.from(logoPng).toString("base64")}",
}
`;
fs.writeFileSync(path.join(ROOT, "src", "UiAssets.luau"), lua);
console.log(`icons ${iconsPng.length} B, logo ${logoPng.length} B, ${ICONS.length} icons`);
